// MARK: - ParsedItem

struct ParsedItem: Identifiable, Hashable, Sendable, Codable {
    var id        : UUID = UUID()
    let title     : String
    let pageURL   : URL
    let thumbnail : URL?
    let duration  : String
    let extra     : String

    enum CodingKeys: String, CodingKey {
        case title, pageURL, thumbnail, duration, extra
    }
    init(title: String, pageURL: URL, thumbnail: URL?, duration: String, extra: String) {
        self.title = title; self.pageURL = pageURL
        self.thumbnail = thumbnail; self.duration = duration; self.extra = extra
    }
    init(from decoder: Decoder) throws {
        let c     = try decoder.container(keyedBy: CodingKeys.self)
        title     = try c.decode(String.self, forKey: .title)
        pageURL   = try c.decode(URL.self,    forKey: .pageURL)
        thumbnail = try c.decodeIfPresent(URL.self, forKey: .thumbnail)
        duration  = try c.decode(String.self, forKey: .duration)
        extra     = try c.decode(String.self, forKey: .extra)
    }
}

// MARK: - ItemKind

enum ItemKind: Sendable {
    case video    // tap → VideoDetailView
    case navLink  // tap → new SiteGalleryView
    case comic    // tap → ComicDetailView

    var stringValue: String {
        switch self {
        case .video:   "video"
        case .navLink: "navLink"
        case .comic:   "comic"
        }
    }

    init?(string: String) {
        switch string {
        case "video":   self = .video
        case "navLink": self = .navLink
        case "comic":   self = .comic
        default:        return nil
        }
    }
}

extension BrowserLayout {
    static func defaultLayout(for kind: ItemKind) -> BrowserLayout {
        switch kind {
        case .video: .bento
        case .comic: .portrait
        case .navLink: .list
        }
    }
}

// MARK: - PaginationMode

enum PaginationMode: Sendable {
    case none
    /// Navigate WKWebView to the URL returned by nextPageJS (sync JS → href string or null).
    case webNavigation(nextPageJS: String)
    /// Fetch page N via callAsyncJavaScript. JS body receives `page` Int, returns JSON string.
    /// Optional `thumbnailJS` runs AFTER items are displayed; returns JSON `{"pageURL":"dataURI",...}`.
    case ajax(js: String, thumbnailJS: String? = nil)

    var typeString: String {
        switch self {
        case .none:           "none"
        case .webNavigation:  "webNavigation"
        case .ajax:           "ajax"
        }
    }

    var js: String? {
        switch self {
        case .none:                     nil
        case .webNavigation(let js):    js
        case .ajax(let js, _):          js
        }
    }
}

// MARK: - SiteParser  (4-phase script pipeline)
//
// Phase 1 · preNavigate  (optional)
//   Runs after every page load. Returns a URL string → navigate there silently and repeat.
//   Returns null/empty → proceed to phase 2.
//   Used for pages requiring an intermediate navigation step.
//
// Phase 2 · wait
//   Seconds to pause after the page settles, giving JS/lazy-load time to finish.
//
// Phase 3 · extractItems
//   Synchronous JS. Returns JSON string:
//     [{ "title":"", "url":"", "thumbnail":"", "duration":"", "extra":"" }]
//   Responsible for: selector logic, thumbnail extraction, deduplication.
//   Each site owns its own approach here — no forced generic fallback.
//
// Phase 4 · paginate
//   How to fetch subsequent pages (.none / .webNavigation / .ajax).

/// Category link shown as a chip bar above the gallery grid.
struct SiteParserCategory: Sendable {
    let name: String
    let urlString: String
}

struct SiteParser: Sendable {
    let hostPattern   : String
    let itemKind      : ItemKind

    // ── Phase 1 ──────────────────────────────────────────────────────────
    let preNavigateJS : String?

    // ── Phase 2 ──────────────────────────────────────────────────────────
    let waitSeconds   : Double

    // ── Phase 3 ──────────────────────────────────────────────────────────
    let extractItemsJS: String

    // ── Phase 4 ──────────────────────────────────────────────────────────
    let paginationMode: PaginationMode

    // ── Optional: sub-categories for gallery picker ──────────────────────
    let categories    : [SiteParserCategory]

    /// When true, skip URLSession fast-load and let WebView render with JS.
    /// Required for sites where thumbnails are generated by JS (e.g. base64 conversion).
    let needsJS       : Bool

    /// Stable portal URL for dynamic domain resolution.
    /// If set, PageLoader fetches this URL first, extracts the real content domain,
    /// and replaces the host in the target URL before loading.
    let portalURL     : String?

    var definitionID: String?
    var ruleID: String?
    var portal: SitePortal?
    var transformScript: String?
    var requestHeaders: [String: String] = [:]
    var presentation: SitePresentation = .init()

    func cacheURL(for url: URL) -> URL {
        let signature = (definitionID ?? "generic") + extractItemsJS + itemKind.stringValue + galleryLayout.rawValue
        let hash = SHA256.hash(data: Data(signature.utf8)).map { String(format: "%02x", $0) }.joined()
        var components = URLComponents(url: url, resolvingAgainstBaseURL: true)
        components?.fragment = "cove-rule-" + hash
        return components?.url ?? url
    }

    /// Visual layout style for the gallery grid.
    /// Defaults to the natural layout for `itemKind` (video→bento, comic→portrait, navLink→list).
    let galleryLayout : BrowserLayout

    /// URL template for keyword search. Use `{keyword}` as placeholder.
    /// e.g. `/search/{keyword}/`, `/?s={keyword}`
    /// nil = search not supported for this site.
    let searchURLTemplate: String?

    init(hostPattern: String, itemKind: ItemKind, preNavigateJS: String? = nil,
         waitSeconds: Double, extractItemsJS: String, paginationMode: PaginationMode,
         categories: [SiteParserCategory] = [], needsJS: Bool = false, portalURL: String? = nil,
         galleryLayout: BrowserLayout? = nil, searchURLTemplate: String? = nil) {
        self.hostPattern = hostPattern; self.itemKind = itemKind
        self.preNavigateJS = preNavigateJS; self.waitSeconds = waitSeconds
        self.extractItemsJS = extractItemsJS; self.paginationMode = paginationMode
        self.categories = categories; self.needsJS = needsJS; self.portalURL = portalURL
        self.galleryLayout = galleryLayout ?? .defaultLayout(for: itemKind)
        self.searchURLTemplate = searchURLTemplate
    }

}

// MARK: - Registry

final class SiteParserRegistry: @unchecked Sendable {
    static let shared = SiteParserRegistry()
    private let lock = NSLock()
    private var storedDefinitions: [SiteDefinition] = []

    static var definitions: [SiteDefinition] {
        shared.lock.withLock { shared.storedDefinitions }
    }

    static func replaceDefinitions(_ values: [SiteDefinition]) {
        shared.lock.withLock { shared.storedDefinitions = values }
    }

    static func definition(for url: URL, id: String? = nil) -> SiteDefinition? {
        if let id, let value = definitions.first(where: { $0.id == id }) { return value }
        return definitions.filter { $0.match.matches(url) }
            .sorted { $0.id < $1.id }.first
    }

    static func rule(for url: URL, role: String, definitionID: String? = nil) -> SiteRule? {
        definition(for: url, id: definitionID)?.rule(for: url, role: role)
    }

    static func parser(for urlString: String, definitionID: String? = nil) -> SiteParser {
        guard let url = URL(string: urlString), let definition = definition(for: url, id: definitionID),
              let rule = definition.rule(for: url, role: "catalog") else { return .generic }
        return parser(definition: definition, rule: rule)
    }

    static func parser(definition: SiteDefinition, rule: SiteRule) -> SiteParser {
        let kind = rule.contentType.flatMap(ItemKind.init(string:)) ?? .video
        let pagination: PaginationMode
        if let config = rule.pagination {
            switch config.mode {
            case "ajax": pagination = .ajax(js: config.script ?? "return '[]';", thumbnailJS: config.thumbnailScript)
            case "webNavigation", "nextLink":
                let js: String
                if let expression = config.expression { js = expression }
                else if let script = config.script { js = "(async function(){\n" + script + "\n})()" }
                else {
                    js = "(function(){ const el = document.querySelector(\(SiteScript.json(config.selector ?? "a[rel=next]"))); const value = el?.getAttribute(\(SiteScript.json(config.attribute ?? "href"))); return value ? new URL(value, document.baseURI).href : null; })()"
                }
                pagination = .webNavigation(nextPageJS: js)
            default: pagination = .none
            }
        } else { pagination = .none }
        var parser = SiteParser(hostPattern: definition.id, itemKind: kind,
            preNavigateJS: rule.load?.preNavigateExpression ?? rule.load?.preNavigateScript.map { "(async function(){\n" + $0 + "\n})()" },
            waitSeconds: rule.load?.waitSeconds ?? 0,
            extractItemsJS: rule.extract?.javascript ?? "'[]'", paginationMode: pagination,
            categories: (rule.categories ?? []).map { .init(name: $0.name, urlString: $0.path) },
            needsJS: rule.load?.mode == "webView", portalURL: definition.portal?.url,
            galleryLayout: rule.presentation?.layout.flatMap(BrowserLayout.init(rawValue:)),
            searchURLTemplate: rule.searchURLTemplate)
        parser.definitionID = definition.id
        parser.ruleID = rule.id
        parser.portal = definition.portal
        parser.transformScript = rule.load?.transformScript
        parser.requestHeaders = rule.load?.headers ?? [:]
        parser.presentation = rule.presentation ?? .init()
        return parser
    }
}

// MARK: - SiteParserOverrides (Codable user overrides)

/// All-optional override struct stored as JSON in BookmarkSite.customParserConfig.
/// nil fields = use built-in default. Adding new fields requires no SwiftData migration.
struct SiteParserOverrides: Codable, Sendable, Equatable {
    var itemKind:       String?   // "video" | "navLink" | "comic"
    var preNavigateJS:  String?   // "" = 禁用; nil = 用默认
    var waitSeconds:    Double?
    var extractItemsJS: String?
    var paginationJS:   String?   // AJAX 或 webNavigation 的 JS 内容
    var paginationType: String?   // "none" | "ajax" | "webNavigation"
    var categories:     [CategoryOverride]?
    var needsJS:        Bool?
    var portalURL:      String?   // "" = 禁用; nil = 用默认
    var galleryLayout:  String?   // "bento" | "portrait" | "list"

    struct CategoryOverride: Codable, Sendable, Equatable {
        var name: String
        var path: String
    }

    /// True when every field is nil (no overrides applied).
    var isEmpty: Bool {
        itemKind == nil && preNavigateJS == nil && waitSeconds == nil
        && extractItemsJS == nil && paginationJS == nil && paginationType == nil
        && categories == nil && needsJS == nil && portalURL == nil
        && galleryLayout == nil
    }
}

// MARK: - Override application

extension SiteParser {
    /// Returns a copy of this parser with non-nil overrides applied.
    func applying(_ overrides: SiteParserOverrides?) -> SiteParser {
        guard let o = overrides, !o.isEmpty else { return self }

        // itemKind
        let resolvedItemKind = o.itemKind.flatMap { ItemKind(string: $0) } ?? itemKind

        // preNavigateJS: "" = disable, nil = keep default
        let resolvedPreNav: String?
        if let override = o.preNavigateJS {
            resolvedPreNav = override.isEmpty ? nil : override
        } else {
            resolvedPreNav = preNavigateJS
        }

        // extractItemsJS
        let resolvedExtract = o.extractItemsJS.flatMap { $0.isEmpty ? nil : $0 } ?? extractItemsJS

        // paginationMode
        let resolvedPagination: PaginationMode
        if let pType = o.paginationType {
            switch pType {
            case "none":
                resolvedPagination = .none
            case "ajax":
                resolvedPagination = .ajax(js: o.paginationJS ?? (paginationMode.js ?? ""))
            case "webNavigation":
                resolvedPagination = .webNavigation(nextPageJS: o.paginationJS ?? (paginationMode.js ?? ""))
            default:
                resolvedPagination = paginationMode
            }
        } else if let pJS = o.paginationJS {
            // JS changed but type not specified → keep current type with new JS
            switch paginationMode {
            case .none:            resolvedPagination = .none
            case .ajax:            resolvedPagination = .ajax(js: pJS)
            case .webNavigation:   resolvedPagination = .webNavigation(nextPageJS: pJS)
            }
        } else {
            resolvedPagination = paginationMode
        }

        // categories
        let resolvedCategories: [SiteParserCategory]
        if let cats = o.categories {
            resolvedCategories = cats.map { SiteParserCategory(name: $0.name, urlString: $0.path) }
        } else {
            resolvedCategories = categories
        }

        // portalURL: "" = disable, nil = keep default
        let resolvedPortal: String?
        if let override = o.portalURL {
            resolvedPortal = override.isEmpty ? nil : override
        } else {
            resolvedPortal = portalURL
        }

        // galleryLayout
        let resolvedLayout = o.galleryLayout.flatMap { BrowserLayout(rawValue: $0) } ?? galleryLayout

        var result = SiteParser(
            hostPattern:    hostPattern,
            itemKind:       resolvedItemKind,
            preNavigateJS:  resolvedPreNav,
            waitSeconds:    o.waitSeconds ?? waitSeconds,
            extractItemsJS: resolvedExtract,
            paginationMode: resolvedPagination,
            categories:     resolvedCategories,
            needsJS:        o.needsJS ?? needsJS,
            portalURL:      resolvedPortal,
            galleryLayout:  resolvedLayout,
            searchURLTemplate: searchURLTemplate
        )
        result.definitionID = definitionID
        result.ruleID = ruleID
        if let resolvedPortal {
            var configuration = portal ?? SitePortal(url: resolvedPortal)
            configuration.url = resolvedPortal
            result.portal = configuration
        } else { result.portal = nil }
        result.transformScript = transformScript
        result.requestHeaders = requestHeaders
        result.presentation = presentation
        return result
    }

}
